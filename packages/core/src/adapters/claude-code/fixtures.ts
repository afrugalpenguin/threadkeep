import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import type { FixtureGenerator } from '../types.js';

export const FIXTURE_PROJECT = '/home/alice/projects/demo';
export const FIXTURE_PROJECT_WINDOWS = 'C:\\Users\\alice\\projects\\demo';

export function projectFolderName(cwd: string): string {
  return cwd.replace(/[^A-Za-z0-9]/g, '-');
}

export interface LineBase {
  sessionId: string;
  uuid: string;
  timestamp: string;
  cwd?: string;
}

const base = (b: LineBase) => ({
  parentUuid: null,
  isSidechain: false,
  uuid: b.uuid,
  timestamp: b.timestamp,
  sessionId: b.sessionId,
  cwd: b.cwd ?? FIXTURE_PROJECT,
  gitBranch: 'main',
  version: '0.0.0-fixture',
});

export const line = (value: unknown): string => `${JSON.stringify(value)}\n`;

export const userText = (b: LineBase, content: string | unknown[]) =>
  line({ ...base(b), type: 'user', message: { role: 'user', content } });

// A user line that Claude Code generated itself: pass { isMeta: true } or { isCompactSummary: true }.
export const flaggedUserText = (b: LineBase, content: string | unknown[], flags: Record<string, unknown>) =>
  line({ ...base(b), type: 'user', message: { role: 'user', content }, ...flags });

export const assistant = (b: LineBase, content: unknown[]) =>
  line({ ...base(b), type: 'assistant', message: { role: 'assistant', content } });

export const toolResultLine = (b: LineBase, toolUseId: string, content: unknown, extra: Record<string, unknown> = {}) =>
  line({
    ...base(b),
    type: 'user',
    message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: toolUseId, is_error: false, content }] },
    ...extra,
  });

export const aiTitle = (sessionId: string, title: string) => line({ type: 'ai-title', sessionId, aiTitle: title });

// Writes <root>/<project folder>/<uuid>.jsonl with small synthetic conversations.
export const claudeCodeFixtures: FixtureGenerator = {
  generate({ root, sessions = 2 }) {
    const ids: string[] = [];
    const folder = path.join(root, projectFolderName(FIXTURE_PROJECT));
    fs.mkdirSync(folder, { recursive: true });
    for (let n = 1; n <= sessions; n += 1) {
      const sessionId = randomUUID();
      ids.push(sessionId);
      const at = (s: number) => `2026-01-0${n}T10:00:0${s}.000Z`;
      const toolId = `toolu_demo_${n}`;
      const text =
        userText({ sessionId, uuid: `u${n}-1`, timestamp: at(0) }, `Demo conversation ${n} question`) +
        assistant({ sessionId, uuid: `a${n}-1`, timestamp: at(1) }, [
          { type: 'text', text: `Demo conversation ${n} answer` },
          { type: 'tool_use', id: toolId, name: 'Read', input: { file_path: `${FIXTURE_PROJECT}/readme.md` } },
        ]) +
        toolResultLine({ sessionId, uuid: `u${n}-2`, timestamp: at(2) }, toolId, 'demo file body') +
        aiTitle(sessionId, `Demo conversation ${n}`);
      fs.writeFileSync(path.join(folder, `${sessionId}.jsonl`), text);
    }
    return { sessionIds: ids };
  },
  sample: writeClaudeCodeSample,
};

const SAMPLE_IDS = ['11111111-1111-4111-8111-111111111111', '22222222-2222-4222-8222-222222222222'] as const;

// Fixed demo sessions: a tool use with a file edit, a thinking block, system generated lines, a planted
// secret and one malformed line. Deterministic so documentation output is repeatable.
export function sampleSessions(secret: string): { sessionId: string; text: string }[] {
  const [first, second] = SAMPLE_IDS;
  const b = (sessionId: string, uuid: string, timestamp: string): LineBase => ({ sessionId, uuid, timestamp });
  const editId = 'toolu_demo_edit';
  const one =
    userText(b(first, 'u1-1', '2026-01-01T10:00:00.000Z'), 'Demo conversation 1: rename the helper in utils') +
    assistant(b(first, 'a1-1', '2026-01-01T10:00:01.000Z'), [
      { type: 'thinking', thinking: 'The helper is only used in one file.' },
      { type: 'text', text: 'I will rename the helper and update its caller.' },
      {
        type: 'tool_use',
        id: editId,
        name: 'Edit',
        input: { file_path: `${FIXTURE_PROJECT}/src/utils.ts`, old_string: 'oldName', new_string: 'newName' },
      },
    ]) +
    toolResultLine(b(first, 'u1-2', '2026-01-01T10:00:02.000Z'), editId, 'edit applied', {
      toolUseResult: { filePath: `${FIXTURE_PROJECT}/src/utils.ts` },
    }) +
    userText(b(first, 'u1-3', '2026-01-01T10:00:03.000Z'), `For the deploy step my token is ${secret} so keep it handy`) +
    '{"type":"user","message":{"role":"user","content":"a line that was cut off\n' +
    aiTitle(first, 'Demo conversation 1');
  const two =
    flaggedUserText(b(second, 'u2-0', '2026-01-02T10:00:00.000Z'), 'Caveat: generated by the tool, not typed', { isMeta: true }) +
    userText(b(second, 'u2-1', '2026-01-02T10:00:01.000Z'), 'Demo conversation 2: summarise the readme') +
    assistant(b(second, 'a2-1', '2026-01-02T10:00:02.000Z'), [{ type: 'text', text: 'The readme describes a demo project.' }]) +
    aiTitle(second, 'Demo conversation 2');
  return [
    { sessionId: first, text: one },
    { sessionId: second, text: two },
  ];
}

export function writeClaudeCodeSample({ root, secret }: { root: string; secret: string }): { files: string[] } {
  const folder = projectFolderName(FIXTURE_PROJECT);
  fs.mkdirSync(path.join(root, folder), { recursive: true });
  const files = sampleSessions(secret).map(({ sessionId, text }) => {
    const rel = `${folder}/${sessionId}.jsonl`;
    fs.writeFileSync(path.join(root, rel), text);
    return rel;
  });
  return { files };
}
